export const getTranslation = (language: Language, key: string): string => {
  return translations[language]?.[key] ?? reportDetailAndPreviewTranslations[language]?.[key] ?? reportPhraseTranslationOverrides[language]?.[key] ?? phraseTranslations[language]?.[key] ?? reportPhraseTranslations[language]?.[key] ?? key
}

export const getDefaultLanguage = (): Language => {
  const saved = localStorage.getItem('cashflow_language') as Language | null
  if (saved && languages.some((l) => l.code === saved)) {
    return saved
  }
  return 'en'
}

export const setLanguage = (language: Language) => {
  localStorage.setItem('cashflow_language', language)
}
